import { readdir, readFile, writeFile } from "node:fs/promises";
import matter from "gray-matter";
import MarkdownIt from "markdown-it";
import { CAMPAIGNS } from "../js/campaign-catalogue.js";

const markdown = new MarkdownIt({ html: false });
const source = new URL("../content/sessions/", import.meta.url);
const sections = new Map([
  ["Session Recap", "recap"],
  ["Key Events", "events"],
  ["People Encountered", "people"],
  ["Places Visited", "places"]
]);
const sessions = [];
const ids = new Set();
const orders = new Set();

for (const campaign of await readdir(source, { withFileTypes: true })) {
  if (!campaign.isDirectory()) continue;
  const directory = new URL(campaign.name + "/", source);
  for (const file of (await readdir(directory)).filter(name => name.endsWith(".md")).sort()) {
    const { data, content } = matter(await readFile(new URL(file, directory), "utf8"));
    const orderKey = data.campaign + ":" + data.order;
    if (typeof data.id !== "string" || !/^[a-z0-9-]+$/.test(data.id)
      || data.campaign !== campaign.name || !CAMPAIGNS.some(entry => entry.id === data.campaign)
      || typeof data.title !== "string" || !data.title.trim()
      || !Number.isInteger(data.order) || data.order < 1
      || ids.has(data.id) || orders.has(orderKey)) {
      throw new Error("Invalid or duplicate session metadata in " + campaign.name + "/" + file);
    }
    ids.add(data.id);
    orders.add(orderKey);

    const environment = {};
    const tokens = markdown.parse(content, environment);
    const parts = [];
    for (let index = 0; index < tokens.length; index++) {
      if (tokens[index].type === "heading_open" && tokens[index].tag === "h2" && tokens[index].level === 0) {
        const heading = tokens[index + 1].content;
        if (!sections.has(heading)) throw new Error("Unsupported session heading in " + file + ": " + heading);
        parts.push({ heading, kind: sections.get(heading), tokens: [] });
        index += 2;
      } else {
        if (!parts.length) throw new Error("Expected a session heading in " + file);
        parts.at(-1).tokens.push(tokens[index]);
      }
    }
    const body = parts.filter(part => part.tokens.length).map(({ heading, kind, tokens }) => ({
      heading, kind, html: markdown.renderer.render(tokens, markdown.options, environment)
    }));
    const { id, title, order, realDate, golarionStart, golarionEnd } = data;
    sessions.push({ id, campaign: data.campaign, title, order, realDate, golarionStart, golarionEnd, body });
  }
}

sessions.sort((first, second) => first.campaign.localeCompare(second.campaign) || first.order - second.order);
await writeFile(new URL("../js/session-data.js", import.meta.url),
  "// Generated by npm run build:sessions. Edit the session Markdown instead.\n"
  + "export const SESSIONS = " + JSON.stringify(sessions, null, 2) + ";\n");
